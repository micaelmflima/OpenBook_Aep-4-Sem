CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
    curso VARCHAR(100) NOT NULL, telefone VARCHAR(30) NOT NULL
);
CREATE TABLE itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id), titulo VARCHAR(150) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('LIVRO', 'APOSTILA', 'EQUIPAMENTO')),
    disciplina VARCHAR(100) NOT NULL, disponivel BOOLEAN NOT NULL DEFAULT TRUE,
    numeracao VARCHAR(40), edicao VARCHAR(40), numero_paginas INTEGER,
    tipo_equipamento VARCHAR(100), estado_conservacao VARCHAR(100)
);
CREATE TABLE movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id), item_id BIGINT NOT NULL REFERENCES itens(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('EMPRESTIMO', 'DOACAO')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('EMPRESTADO', 'DEVOLVIDO', 'ATRASADO', 'DOADO')),
    data_solicitacao DATE NOT NULL, prazo_devolucao DATE
);
CREATE TABLE historico_movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movimentacao_id BIGINT NOT NULL REFERENCES movimentacoes(id), status VARCHAR(20) NOT NULL,
    registrado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
